const norm = (s) =>
  (s || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\p{L}]/gu, '');

export const GLOSSARY = {};
Object.keys(RAW).forEach((k) => { GLOSSARY[norm(k)] = RAW[k]; });

export const translateWord = (w) => GLOSSARY[norm(w)] || null;
